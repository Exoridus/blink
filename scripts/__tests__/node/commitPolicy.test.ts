import assert from 'node:assert/strict';
import { spawnSync } from 'node:child_process';
import { test } from 'node:test';

import { messageViolations, addedLineViolations } from '../../lib/commitPolicy.ts';

void test('commitlint does not bypass attribution checks for generated merge messages', () => {
    const result = spawnSync(process.execPath, ['node_modules/@commitlint/cli/cli.js'], {
        input: 'Merge branch topic\n\nCo-authored-by: A <a@example.invalid>',
        encoding: 'utf8',
    });
    assert.notEqual(result.status, 0);
});

void test('commit and PR text reject all co-author trailers and generation attribution', () => {
    assert.deepEqual(messageViolations('fix(runtime): preserve feedback history'), []);
    assert.ok(messageViolations('fix: something\n\nCo-authored-by: A <a@example.com>').length);
    assert.ok(messageViolations('feat: add panel\n\nGenerated by ChatGPT').length);
    assert.ok(messageViolations('feat: add panel\n\n🤖 Generated with Claude Code').length);
    assert.ok(messageViolations('fix: use GPT-6 to update code').length);
    assert.deepEqual(messageViolations('fix: reject malformed JSON'), []);
});

void test('new source provenance is blocked while technical terms and licensing survive', () => {
    assert.ok(addedLineViolations('src/helper.ts', ['// Written by Codex']).length);
    assert.ok(addedLineViolations('docs/blinkfx/custom-effects.md', ['Created with Claude']).length);
    assert.ok(addedLineViolations('src/helper.ts', ['// C:\\Users\\Owner\\private\\file.ts']).length);
    assert.ok(addedLineViolations('src/helper.ts', ['// See .workspace/private-plan.md']).length);
    assert.deepEqual(addedLineViolations('src/helper.ts', ['const model = "gpt-6";']), []);
    assert.deepEqual(addedLineViolations('src/helper.ts', ['// A model matrix transforms positions.']), []);
    assert.deepEqual(addedLineViolations('public/vendor/LICENSE', ['Copyright OpenAI']), []);
    assert.deepEqual(addedLineViolations('AGENTS.md', ['Do not add Co-authored-by trailers.']), []);
});
